def _span(a, b):
    return f"{a:%d.%m}" if a == b else f"{a:%d.%m}–{b:%d.%m}"


def current_term(today):
    """Триместр, внутри которого мы сейчас. До начала года — ближайший будущий."""
    for term in TERMS:
        if today <= term["break"][1]:
            return term
    return TERMS[-1]


def key_dates(today):
    """Ближайшие вехи текущего триместра — то, что показывается на дашборде."""
    term = current_term(today)
    rows = [
        {"date": term["rk1"][0], "title": "Рубежный контроль 1", "kind": "rk",
         "span": _span(*term["rk1"])},
        {"date": term["rk2"][0], "title": "Рубежный контроль 2", "kind": "rk",
         "span": _span(*term["rk2"])},
        {"date": term["study"][1], "title": "Конец теоретического обучения", "kind": "term",
         "span": f"{term['study'][1]:%d.%m}"},
        {"date": term["exams"][0], "title": "Экзаменационная сессия", "kind": "exam",
         "span": _span(*term["exams"])},
        {"date": term["break"][0], "title": "Каникулы", "kind": "break",
         "span": _span(*term["break"])},
    ]
    start, end = term["study"][0], term["break"][1]
    rows += [{"date": day, "title": name, "kind": "holiday", "span": f"{day:%d.%m}"}
             for day, name in HOLIDAYS if start <= day <= end]
    rows.sort(key=lambda r: r["date"])
    return [{**r, "date": r["date"].isoformat()} for r in rows]


def period_of(due, today=None):
    """К какой аттестации отнести задание с этим сроком.

    Веса заданий живут в журнале Moodle, а он на этом сервере закрыт для ajax.
    Но AITU строит триместр по датам, и этого достаточно: всё до конца РК1 —
    первая аттестация, до конца РК2 — вторая, дальше экзамен. Догадка честная и
    ровно одна; если журнал когда-нибудь откроют, она уступит место фактам.
    """
    term = current_term(today or due)
    if due <= term["rk1"][1]:
        return 1
    if due <= term["rk2"][1]:
        return 2
    return "final"
